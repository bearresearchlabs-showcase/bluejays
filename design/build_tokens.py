#!/usr/bin/env python3
"""Compile design/tokens.json to design/tokens.css and bundle design/bluejays.css.

Deterministic: same input JSON always produces byte-identical output, so the
generated files can be committed and diffed. Theme model (three states):
  - bare :root carries the complete light palette;
  - @media (prefers-color-scheme: dark) redefines color tokens under
    :root:not([data-theme="light"]) so system-dark users get dark;
  - :root[data-theme="dark"] redefines them again so an explicit toggle wins
    in both directions.

Usage: python3 design/build_tokens.py
"""
import json
import pathlib

HERE = pathlib.Path(__file__).parent
TOKENS = json.loads((HERE / "tokens.json").read_text())


def flatten_colors(node, prefix=""):
    """Yield (css-var-name, light, dark) for every color leaf."""
    for key, val in node.items():
        name = f"{prefix}-{key}" if prefix else key
        if isinstance(val, dict) and {"light", "dark"} <= set(val):
            yield name, val["light"], val["dark"]
        elif isinstance(val, dict):
            yield from flatten_colors(val, name)


def emit():
    colors = list(flatten_colors(TOKENS["color"]))
    lines = [
        "/* GENERATED by design/build_tokens.py from design/tokens.json — do not edit by hand. */",
        f"/* {TOKENS['name']} v{TOKENS['version']} */",
        "",
        ":root {",
    ]
    for name, light, _ in colors:
        lines.append(f"  --{name}: {light};")
    for group in ("font", "text-scale", "space", "radius", "line-height", "layout"):
        prefix = {"text-scale": "text", "line-height": "leading"}.get(group, group)
        for key, val in TOKENS[group].items():
            lines.append(f"  --{prefix}-{key}: {val};")
    lines.append("}")

    dark_block = [f"    --{name}: {dark};" for name, _, dark in colors]
    lines += [
        "",
        "@media (prefers-color-scheme: dark) {",
        '  :root:not([data-theme="light"]) {',
        *dark_block,
        "  }",
        "}",
        "",
        ':root[data-theme="dark"] {',
        *[f"  --{name}: {dark};" for name, _, dark in colors],
        "}",
        "",
    ]
    css = "\n".join(lines)
    (HERE / "tokens.css").write_text(css)

    components = (HERE / "components.css").read_text()
    bundle = css + "\n" + components
    (HERE / "bluejays.css").write_text(bundle)
    print(f"tokens.css: {len(css)} bytes · bluejays.css: {len(bundle)} bytes · {len(colors)} color tokens")


if __name__ == "__main__":
    emit()
